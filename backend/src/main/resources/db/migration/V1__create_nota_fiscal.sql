CREATE TABLE nota_fiscal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero BIGINT NOT NULL,
    serie VARCHAR(10) NOT NULL,
    emitente_cnpj VARCHAR(14) NOT NULL,
    emitente_razao_social VARCHAR(180) NOT NULL,
    destinatario_documento VARCHAR(14) NOT NULL,
    destinatario_nome VARCHAR(180) NOT NULL,
    descricao VARCHAR(500) NOT NULL,
    valor DECIMAL(15, 2) NOT NULL,
    data_emissao TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL,
    codigo_verificacao VARCHAR(32) NOT NULL,
    CONSTRAINT uk_nota_numero_serie UNIQUE (numero, serie)
);

CREATE INDEX idx_nota_data_emissao ON nota_fiscal (data_emissao DESC);
